class SocialNetworkEventHandler(BaseEventHandler):
    """社交网络事件处理器 / Social Network Event Handler"""

    event_type = EventType.ON_MESSAGE
    handler_name = "life_simulation_social_network"
    handler_description = "Process social network interactions / 处理社交网络互动"
    weight = 5

    async def execute(self, message: MaiMessages | None) -> Tuple[bool, bool, Optional[str], None, None]:
        if not _plugin_instance or not message:
            return True, True, None, None, None

        # 检查是否启用社交网络 / Check if social network is enabled
        if not _plugin_instance._social_network or not _plugin_instance._social_network.is_enabled():
            return True, True, None, None, None

        # 检查是否处于睡眠状态 / Check if in sleep state
        # 睡眠期间不记录互动，避免增加亲密度
        sleep_state = _plugin_instance._state.sleep_state
        if sleep_state not in [SleepState.AWAKE, SleepState.SLEEPY]:
            logger.debug(f"[SOCIAL] Skipping interaction recording during sleep state: {sleep_state.value}")
            return True, True, None, None, None

        # 检查是否为 notice 消息 / Check if it's a notice message
        # notice 消息（如群消息撤回通知）不应该触发社交互动记录
        sub_type = message.message_base_info.get("sub_type", "") if hasattr(message, 'message_base_info') else ""
        if sub_type:
            logger.debug(f"[SOCIAL] Skipping notice message with sub_type: {sub_type}")
            return True, True, None, None, None

        # 检查是否是与bot的对话 / Check if message is directed to bot
        # 只有在以下情况下才记录互动和判定亲密度：
        # 1. 私聊消息（所有私聊都是与bot的对话）
        # 2. 群聊中@了bot或提及了bot
        is_mentioned = getattr(message, "is_mentioned", False)
        is_at = getattr(message, "is_at", False)
        is_private = message.is_private_message
        
        if not is_private and not is_mentioned and not is_at:
            logger.debug(f"[SOCIAL] Skipping message not directed to bot (not private, not mentioned, not at)")
            return True, True, None, None, None

        try:
            # 获取发送者信息 / Get sender information
            user_id = str(message.message_base_info.get("user_id", "")) if hasattr(message, 'message_base_info') else ""
            user_name = message.message_base_info.get("user_nickname", "Unknown") if hasattr(message, 'message_base_info') else "Unknown"
            message_content = message.plain_text if hasattr(message, 'plain_text') else ""

            if not user_id:
                return True, True, None, None, None

            # 添加或更新用户 / Add or update user
            await _plugin_instance._social_network.add_or_update_user(user_id, user_name)

            # 记录互动 / Record interaction
            await _plugin_instance._social_network.record_interaction(
                user_id, "message", message_content, _plugin_instance
            )

        except Exception as e:
            logger.error(f"Error in social network event handler: {e}")

        return True, True, None, None, None


class MessageSleepEventHandler(BaseEventHandler):
    """睡眠消息事件处理器 / Sleep Message Event Handler"""

    event_type = EventType.ON_MESSAGE
    handler_name = "life_simulation_sleep"
    handler_description = "Handle sleep state and block messages during sleep / 处理睡眠状态，睡眠期间拦截消息"
    weight = 100  # 高优先级，在其他处理器之前执行
    intercept_message = True  # 标记为消息拦截类型处理器

    async def execute(self, message: MaiMessages | None) -> Tuple[bool, bool, Optional[str], None, None]:
        if not _plugin_instance or not message:
            return True, True, None, None, None

        # 检查是否启用睡眠系统 / Check if sleep system is enabled
        sleep_enabled = _plugin_instance.get_config("sleep.enabled", True)
        if not sleep_enabled:
            return True, True, None, None, None

        # 检查是否是 Dream 功能发送的消息 / Check if message is from Dream system
        # Dream 功能通常使用特定的发送者ID或消息类型
        is_dream_message = False
        if hasattr(message, 'message_base_info'):
            # 检查发送者ID是否为机器人自己（Dream系统通常以机器人身份发送）
            sender_id = message.message_base_info.get("user_id", "")
            bot_id = message.message_base_info.get("self_id", "")
            if sender_id == bot_id:
                # 是机器人自己发送的消息，可能是Dream系统
                is_dream_message = True
                logger.debug(f"[SLEEP] Message from bot (possibly Dream), allowing through")

        # 如果是 Dream 消息，不拦截 / If Dream message, don't intercept
        if is_dream_message:
            return True, True, None, None, None

        # 检查当前睡眠状态 / Check current sleep state
        sleep_state = _plugin_instance._state.sleep_state

        # 获取当前时间和日程 / Get current time and schedule
        current_time = await _plugin_instance._time_api.get_current_time()
        schedule = _plugin_instance._state.schedule
        
        # 查找当前日程活动 / Find current schedule activity
        current_activity_is_sleep = False
        if schedule:
            current_hour = current_time.hour
            current_minute = current_time.minute
            current_time_minutes = current_hour * 60 + current_minute
            
            # 查找当前时间的日程活动 / Find schedule activity for current time
            for activity in schedule:
                start_time_str = activity.get("start_time", "")
                end_time_str = activity.get("end_time", "")
                if ":" in start_time_str and ":" in end_time_str:
                    try:
                        start_hour, start_minute = map(int, start_time_str.split(":"))
                        end_hour, end_minute = map(int, end_time_str.split(":"))
                        start_time_minutes = start_hour * 60 + start_minute
                        end_time_minutes = end_hour * 60 + end_minute
                        
                        # 处理跨天情况 / Handle cross-day case (e.g., 23:00-07:00)
                        is_cross_day = end_time_minutes < start_time_minutes
                        in_time_range = False
                        
                        if is_cross_day:
                            # 跨天:当前时间 >= 开始时间 或 当前时间 < 结束时间
                            in_time_range = (current_time_minutes >= start_time_minutes) or (current_time_minutes < end_time_minutes)
                        else:
                            # 不跨天:正常比较
                            in_time_range = start_time_minutes <= current_time_minutes < end_time_minutes
                        
                        # 如果当前时间在活动时间段内 / If current time is within activity time slot
                        if in_time_range:
                            activity_type = activity.get("activity_type", "")
                            if activity_type == "sleep":
                                current_activity_is_sleep = True
                            break
                    except (ValueError, IndexError) as e:
                        logger.warning(f"[SCHEDULE] Failed to parse activity time {start_time_str}-{end_time_str}: {e}")
        
        # 根据日程同步睡眠状态 / Sync sleep state with schedule
        if current_activity_is_sleep:
            # 日程是睡眠活动，如果是清醒状态应该进入睡眠 / Schedule is sleep, should enter sleep if awake
            if sleep_state in [SleepState.AWAKE, SleepState.SLEEPY]:
                logger.info(f"[SCHEDULE] Current activity is sleep, entering sleep state")
                async with _plugin_instance._state_lock:
                    _plugin_instance._state.sleep_state = SleepState.FALLING_ASLEEP
                    _plugin_instance._state.last_sleep_time = current_time.timestamp()
                    logger.info(f"[SLEEP] State changed: {sleep_state.value} -> FALLING_ASLEEP")
                sleep_state = SleepState.FALLING_ASLEEP
        else:
            # 日程不是睡眠活动，如果是睡眠状态应该唤醒 / Schedule is not sleep, should wake up if sleeping
            if sleep_state not in [SleepState.AWAKE, SleepState.SLEEPY]:
                logger.info(f"[SCHEDULE] Current activity is not sleep, waking up from {sleep_state.value}")
                async with _plugin_instance._state_lock:
                    _plugin_instance._state.sleep_state = SleepState.AWAKE
                    _plugin_instance._state.last_wake_time = current_time.timestamp()
                    logger.info(f"[SLEEP] State changed: {sleep_state.value} -> AWAKE (schedule sync)")
                sleep_state = SleepState.AWAKE
        
