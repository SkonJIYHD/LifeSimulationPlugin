class HolidayAPI:
    """节日API / Holiday API"""

    def __init__(self, config: Dict[str, Any]):
        self.enabled = config.get("enabled", True)
        self.url_template = config.get("url", "https://timor.tech/api/holiday/info/{date}")
        self.cache_duration = config.get("cache_duration", 86400)
        self.timeout = config.get("timeout", 5)
        self.cache: Dict[str, str] = {}

    async def get_holiday(self, date_obj: date) -> Tuple[str, bool]:
        """获取节日信息 / Get holiday information"""
        if not self.enabled:
            return "", False

        date_str = date_obj.strftime("%Y-%m-%d")

        # Check cache / 检查缓存
        if date_str in self.cache:
            return self.cache[date_str], True

        # Use holiday API / 使用节日API
        try:
            url = self.url_template.replace("{date}", date_str)
            async with aiohttp.ClientSession() as session:
                async with session.get(url, timeout=self.timeout) as response:
                    if response.status == 200:
                        data = await response.json()
                        if data.get("code") == 0:
                            holiday = data.get("holiday", None)
                            if holiday:
                                holiday_name = holiday.get("name", "")
                                self.cache[date_str] = holiday_name
                                return holiday_name, True
        except Exception as e:
            logger.warning(f"Failed to fetch holiday info: {e}")

        # Check for common holidays manually / 手动检查常见节日
        holiday = self._check_common_holidays(date_obj)
        if holiday:
            self.cache[date_str] = holiday
            return holiday, True

        self.cache[date_str] = ""
        return "", False

    def _check_common_holidays(self, date_obj: date) -> str:
        """检查常见节日 / Check common holidays"""
        month = date_obj.month
        day = date_obj.day

        # Chinese holidays / 中国节日
        if month == 1 and day == 1:
            return "元旦"
        elif month == 2 and 14 <= day <= 20:  # Spring Festival (approximate)
            return "春节"
        elif month == 4 and 4 <= day <= 6:  # Qingming Festival
            return "清明节"
        elif month == 5 and 1 == day:
            return "劳动节"
        elif month == 6 and day in [22, 23]:  # Dragon Boat Festival (approximate)
            return "端午节"
        elif month == 10 and 1 == day:
            return "国庆节"

        # Western holidays / 西方节日
        elif month == 12 and 25 == day:
            return "圣诞节"
        elif month == 2 and 14 == day:
            return "情人节"

        return ""


