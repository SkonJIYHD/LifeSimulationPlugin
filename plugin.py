class TimeAPI:
    """时间API / Time API"""

    def __init__(self, config: Dict[str, Any]):
        self.method = config.get("method", "builtin")
        self.url = config.get("url", "")
        self.timeout = config.get("timeout", 5)

    async def get_current_time(self) -> datetime:
        """获取当前时间 / Get current time"""
        if self.method == "custom" and self.url:
            try:
                async with aiohttp.ClientSession() as session:
                    async with session.get(self.url, timeout=self.timeout) as response:
                        if response.status == 200:
                            data = await response.json()
                            # 尝试解析常见的datetime字段
                            if "datetime" in data:
                                return datetime.fromisoformat(data["datetime"].replace("Z", "+00:00"))
                            elif "unixtime" in data:
                                return datetime.fromtimestamp(data["unixtime"])
            except Exception as e:
                logger.warning(f"Failed to fetch time from custom API: {e}")

        # 默认使用内置datetime / Default to built-in datetime
        return datetime.now()


