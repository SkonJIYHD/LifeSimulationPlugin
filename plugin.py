    def _create_tracked_task(self, coro, task_name: str = "unknown") -> asyncio.Task:
        """创建并跟踪后台任务 / Create and track background task"""
        async def _task_wrapper():
            try:
                logger.debug(f"Task started: {task_name}")
                return await coro
            except asyncio.CancelledError:
                logger.info(f"Task cancelled: {task_name}")
                raise
            except Exception as exc:
                logger.error(f"Task failed: {task_name}, error: {exc}", exc_info=True)
                raise

        task = asyncio.create_task(_task_wrapper())

        def _on_task_done(t: asyncio.Task):
            async def _cleanup():
                async with self._tasks_lock:
                    if t in self._background_tasks:
                        self._background_tasks.discard(t)
                        logger.debug(f"Task removed from tracking: {task_name} (remaining: {len(self._background_tasks)})")
                    if t.exception():
                        logger.warning(f"Task {task_name} completed with exception: {t.exception()}")

            try:
                loop = asyncio.get_running_loop()
                if loop.is_running():
                    cleanup_task = asyncio.create_task(_cleanup())
                    cleanup_task.add_done_callback(
                        lambda t: logger.error(f"Cleanup task failed: {t.exception()}", exc_info=True)
                        if t.exception() else None
                    )
            except RuntimeError:
                logger.warning(f"Cannot get event loop, task cleanup may fail: {task_name}")

        task.add_done_callback(_on_task_done)

        async def _add_task():
            async with self._tasks_lock:
                self._background_tasks.add(task)
                logger.debug(f"Task added to tracking: {task_name} (total: {len(self._background_tasks)})")

        try:
            loop = asyncio.get_running_loop()
            if loop.is_running():
                add_task_task = asyncio.create_task(_add_task())
                add_task_task.add_done_callback(
                    lambda t: logger.error(f"Add task failed: {t.exception()}", exc_info=True)
                    if t.exception() else None
                )
        except RuntimeError:
            logger.warning(f"Cannot get event loop, task may not be tracked: {task_name}")

        return task

