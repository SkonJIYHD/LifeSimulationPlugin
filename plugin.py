    async def _update_states(self):
        """更新状态 / Update states"""
        async with self._state_lock:
            current_time = await self._time_api.get_current_time()
            date_str = current_time.strftime("%Y-%m-%d")
            time_delta = current_time.timestamp() - self._state.last_update if self._state.last_update > 0 else 0

            if time_delta < 60:  # Only update if at least 1 minute has passed
                return

        # Check if need to regenerate schedule / 检查是否需要重新生成日程
        regenerate_daily = self.get_config("schedule.regenerate_daily", True)
        if regenerate_daily and self._state.schedule_generated_date != date_str:
            await self._generate_schedule()

        # Check for random events / 检查随机事件
        random_event_probability = self.get_config("schedule.random_event_probability", 0.1)
        if random.random() < random_event_probability:
            event = await self._generate_random_event()
            if event:
                await self._handle_event(event)

        # Judge emotion / 判断情绪
        await self._judge_emotion()

        async with self._state_lock:
            self._state.last_update = current_time.timestamp()

    async def _handle_event(self, event: Dict[str, Any]):
        """处理事件 / Handle event"""
        try:
            # Apply impacts / 应用影响
            health_impact = event.get("health_impact", 0)
            fatigue_impact = event.get("fatigue_impact", 0)
            hunger_impact = event.get("hunger_impact", 0)
            emotion_impact = event.get("emotion_impact", 0)

            old_health_status = self._state.health_status

            async with self._state_lock:
                self._state.health = max(0, min(100, self._state.health + health_impact))
                self._state.fatigue = max(0, min(100, self._state.fatigue + fatigue_impact))
                self._state.hunger = max(0, min(100, self._state.hunger + hunger_impact))
                self._state.emotion_intensity = max(0, min(100, self._state.emotion_intensity + emotion_impact))

                # Update health status / 更新健康状态
                # 健康度越高越健康 / Higher health value means healthier
                if self._state.health >= 80:
                    self._state.health_status = HealthStatus.HEALTHY
                elif self._state.health >= 60:
                    self._state.health_status = HealthStatus.RECOVERING
                elif self._state.health >= 40:
                    self._state.health_status = HealthStatus.SLIGHTLY_ILL
                elif self._state.health >= 20:
                    self._state.health_status = HealthStatus.ILL
                else:
                    self._state.health_status = HealthStatus.SERIOUSLY_ILL

            # Check if health status changed / 检查健康状态是否变化
            new_health_status = self._state.health_status
            if old_health_status != new_health_status:
                logger.info(f"Health status changed: {old_health_status.value} -> {new_health_status.value}")

                # If became ill, regenerate schedule based on new health status
                # 如果生病了，根据新的健康状态重新生成日程
                if new_health_status != HealthStatus.HEALTHY:
                    logger.info(f"Regenerating schedule due to illness: {new_health_status.value}")
                    await self._generate_schedule()
                # If recovered, regenerate schedule
                # 如果康复了，重新生成日程
                elif old_health_status != HealthStatus.HEALTHY:
                    logger.info("Regenerating schedule after recovery")
                    await self._generate_schedule()

            logger.info(f"Handled event: {event.get('event_name')}, impacts: health={health_impact}, fatigue={fatigue_impact}, hunger={hunger_impact}, emotion={emotion_impact}")
        except Exception as e:
            logger.error(f"Failed to handle event: {e}", exc_info=True)

    async def _save_state(self):
        """保存状态 / Save state"""
        try:
            state_data = self._state.to_dict()
            with open(self._state_file, 'w', encoding='utf-8') as f:
                json.dump(state_data, f, indent=2, ensure_ascii=False)
        except Exception as e:
            logger.error(f"Failed to save state: {e}", exc_info=True)

    async def _load_state(self):
        """加载状态 / Load state"""
        try:
            if self._state_file.exists():
                with open(self._state_file, 'r', encoding='utf-8') as f:
                    state_data = json.load(f)
                self._state.from_dict(state_data)
                logger.info("State loaded successfully")
        except Exception as e:
            logger.error(f"Failed to load state: {e}", exc_info=True)

